CREATE TABLE task_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL CONSTRAINT task_user_email_unique UNIQUE,
    password_hash VARCHAR(60) NOT NULL
);

ALTER TABLE task_item ADD COLUMN owner_id BIGINT
    CONSTRAINT task_item_owner_fk REFERENCES task_user (id);

CREATE INDEX task_item_owner_idx ON task_item (owner_id, id);

CREATE TABLE task_demo_claim (
    task_id BIGINT PRIMARY KEY,
    recipient_email VARCHAR(254) NOT NULL,
    claimed_at TIMESTAMP WITH TIME ZONE
);

